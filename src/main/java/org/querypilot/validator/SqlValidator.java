package org.querypilot.validator;

import org.querypilot.dto.SqlValidationResult;
import org.springframework.stereotype.Component;

import java.util.Locale;

@Component
public class SqlValidator {

    public SqlValidationResult validate(String sql) {

        if (sql == null || sql.trim().isEmpty()) {
            return new SqlValidationResult(
                    false,
                    "SQL query cannot be empty",
                    null
            );
        }

        String normalizedSql = normalize(sql);

        if (normalizedSql.isEmpty()) {
            return new SqlValidationResult(
                    false,
                    "SQL query cannot be empty",
                    null
            );
        }

        String upperSql = normalizedSql.toUpperCase(Locale.ROOT);

        // Only SELECT queries are allowed.
        if (!upperSql.startsWith("SELECT ")) {
            return new SqlValidationResult(
                    false,
                    "Only SELECT statements are allowed",
                    normalizedSql
            );
        }

        // Prevent multiple SQL statements.
        if (normalizedSql.contains(";")) {
            return new SqlValidationResult(
                    false,
                    "Multiple SQL statements are not allowed",
                    normalizedSql
            );
        }

        // Block potentially dangerous SQL operations.
        String[] blockedKeywords = {
                "INSERT ",
                "UPDATE ",
                "DELETE ",
                "DROP ",
                "ALTER ",
                "TRUNCATE ",
                "CREATE ",
                "GRANT ",
                "REVOKE ",
                "EXEC ",
                "EXECUTE "
        };

        for (String keyword : blockedKeywords) {
            if (upperSql.contains(keyword)) {
                return new SqlValidationResult(
                        false,
                        "Unsupported or potentially dangerous SQL operation detected",
                        normalizedSql
                );
            }
        }

        return new SqlValidationResult(
                true,
                "SQL query is valid and supported",
                normalizedSql
        );
    }

    private String normalize(String sql) {

        String normalized = sql.trim();

        // Remove Markdown SQL code fences generated by an LLM.
        if (normalized.startsWith("```sql")) {
            normalized = normalized.substring(6).trim();
        } else if (normalized.startsWith("```")) {
            normalized = normalized.substring(3).trim();
        }

        if (normalized.endsWith("```")) {
            normalized = normalized.substring(
                    0,
                    normalized.length() - 3
            ).trim();
        }

        // Remove a single trailing semicolon.
        if (normalized.endsWith(";")) {
            normalized = normalized.substring(
                    0,
                    normalized.length() - 1
            ).trim();
        }

        // Normalize whitespace.
        normalized = normalized.replaceAll("\\s+", " ");

        return normalized;
    }
}